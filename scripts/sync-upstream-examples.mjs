import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const bundle = resolve(process.env.JSONFORMS_EXAMPLES_BUNDLE ??
  '../jsonforms/packages/examples/lib/jsonforms-examples.cjs.js');
const packageFile = resolve(dirname(bundle), '..', 'package.json');
const { getExamples } = createRequire(import.meta.url)(bundle);
const examples = getExamples();
const version = JSON.parse(readFileSync(packageFile, 'utf8')).version;
const upstreamRoot = resolve(dirname(bundle), '../../..');
const commit = process.env.JSONFORMS_UPSTREAM_COMMIT ??
  (execFileSync('git', ['log', '-1', '--format=%H', `--grep=^v${version}$`],
    { cwd: upstreamRoot, encoding: 'utf8' }).trim() ||
   execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstreamRoot, encoding: 'utf8' }).trim());
const directory = resolve('examples/src/commonMain/kotlin/com/chobantonov/jsonfroms/examples/upstream');
mkdirSync(directory, { recursive: true });
const pascalName = (name) => name.split(/[^a-zA-Z0-9]+/).filter(Boolean)
  .map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const fileName = (name) => `${/^[0-9]/.test(name) ? 'Upstream' : ''}${pascalName(name)}Example.kt`;
const propertyName = (name) => `upstream${pascalName(name)}Example`;
const files = new Set(examples.map(({ name }) => fileName(name)));
if (files.size !== examples.length) throw new Error('Example names collide after conversion to Kotlin filenames');
for (const file of readdirSync(directory)) {
  if (file.endsWith('.kt') && !files.has(file) && file !== 'UpstreamExamples.kt')
    rmSync(join(directory, file));
}
const quoted = (value) => JSON.stringify(value).replaceAll('$', '\\$');
const rawJson = (value) => {
  const json = JSON.stringify(value, null, 2);
  if (json.includes('"""')) throw new Error('A JSON value contains a Kotlin raw string delimiter');
  const lines = json.replaceAll('$', () => "${'$'}")
    .split('\n').map((line) => `        ${line}`).join('\n');
  return `"""\n${lines}\n        """.trimIndent()`;
};
for (const example of examples) {
  const fields = [
    `        name = ${quoted(example.name)},`,
    `        label = ${quoted(example.label)},`,
    ...(['data', 'schema', 'uischema', 'config'].filter((key) => example[key] !== undefined)
      .map((key) => `        ${key === 'uischema' ? 'uischemaJson' : `${key}Json`} = ${rawJson(example[key])},`)),
  ].join('\n');
  const actions = example.actions?.map(({ label }) => label).join(', ');
  writeFileSync(join(directory, fileName(example.name)),
`// Generated from @jsonforms/examples ${version} (${commit}).
${actions ? `// Interactive actions: ${actions}\n` : ''}package com.chobantonov.jsonfroms.examples

internal val ${propertyName(example.name)}: ExampleDescription by lazy {
    upstreamExample(
${fields}
    )
}
`);
}
const names = examples.map(({ name }) => `    ${quoted(name)},`).join('\n');
const properties = examples.map(({ name }) => `    ${propertyName(name)},`).join('\n');
writeFileSync(join(directory, 'UpstreamExamples.kt'),
`// Generated by scripts/sync-upstream-examples.mjs from @jsonforms/examples ${version} (${commit}).
package com.chobantonov.jsonfroms.examples

const val upstreamExamplesVersion = "${version}"
const val upstreamExamplesCommit = "${commit}"

internal val upstreamExampleNames: Set<String> = setOf(
${names}
)

internal val upstreamExamples: List<ExampleDescription> by lazy { listOf(
${properties}
) }
`);
console.log(`Synchronized ${examples.length} examples from @jsonforms/examples ${version}`);
